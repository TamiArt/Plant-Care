import type { AssistantContext } from "./localAssistant";

const normalize = (value: string) => value.toLocaleLowerCase("ru-RU").replace(/ё/g, "е");
const hasAny = (text: string, words: string[]) => words.some(word => text.includes(word));
const plantName = (context?: AssistantContext) => context?.name ? `«${context.name}»` : "растения";

export interface OfflineAnswer {
  text: string;
  topic: string;
}

export function answerWithOfflineKnowledge(question: string, context?: AssistantContext): OfflineAnswer {
  const q = normalize(question);
  const name = plantName(context);

  if (hasAny(q, ["желте", "желтый", "желтизн"])) return {
    topic: "yellow-leaves",
    text: `У ${name} пожелтение чаще связано с изменением полива, света или естественным старением листа. Сравните, когда был последний полив, не стоит ли вода в поддоне и не изменилось ли освещение. Если желтеет один нижний старый лист — это может быть нормой; массовое пожелтение лучше записать как наблюдение и проверить динамику через несколько дней.`,
  };

  if (hasAny(q, ["полив", "поливать", "воды", "засох", "сохнет"])) return {
    topic: "watering",
    text: context?.wateringInterval
      ? `Для ${name} сейчас установлен интервал ${context.wateringInterval} дн. Ориентируйтесь на историю именно этого растения и сезон: если состояние ухудшается, измените интервал вручную небольшим шагом и наблюдайте несколько циклов. Не увеличивайте объём и частоту одновременно — так будет понятнее, что помогло.`
      : `Для ${name} задайте стартовый интервал по проверенной карточке вида, затем корректируйте его по собственной истории. Меняйте только один параметр за раз и фиксируйте результат, чтобы не потерять причинно-следственную связь.`,
  };

  if (hasAny(q, ["пересад", "горш", "грунт", "субстрат"])) return {
    topic: "repotting",
    text: `Пересадка ${name} обычно нужна, когда корни заполнили горшок, субстрат потерял структуру или вода проходит необычно быстро. Новый горшок берите лишь немного больше предыдущего и сохраняйте подходящий дренаж. После пересадки запишите дату и не сочетайте её сразу с другими стрессовыми изменениями.`,
  };

  if (hasAny(q, ["удобрен", "подкорм", "кормить"])) return {
    topic: "fertilizing",
    text: `Подкормку ${name} безопаснее планировать в период активного роста и по инструкции конкретного удобрения. Не компенсируйте удобрением недостаток света или проблемы с корнями и не превышайте дозировку. Запишите внесение в историю, чтобы не повторить его случайно.`,
  };

  if (hasAny(q, ["свет", "солнц", "окн", "ламп"])) return {
    topic: "light",
    text: `Оцените освещение ${name} по изменениям роста: вытягивание и мелкие новые листья часто сопровождают недостаток света, а выцветание и сухие пятна могут появляться при слишком резком прямом солнце. Переставляйте растение постепенно и фиксируйте дату изменения места.`,
  };

  if (hasAny(q, ["вредител", "клещ", "тля", "мошк", "щитов", "червец"])) return {
    topic: "pests",
    text: `Изолируйте ${name} от остальных растений и осмотрите обе стороны листьев, пазухи и поверхность грунта. Сделайте фото, запишите наблюдение и проверьте соседние растения. Не смешивайте средства обработки и следуйте только инструкции производителя; при сомнении сначала используйте механическое удаление и уточните вид вредителя.`,
  };

  if (hasAny(q, ["размнож", "черен", "укорен", "детк"])) return {
    topic: "propagation",
    text: `Способ размножения зависит от вида ${name}: черенок, деление, детки или семена. Используйте чистый инструмент, подпишите дату и держите новое растение отдельно в период укоренения. Для точного способа сверяйтесь с проверенной карточкой конкретного вида.`,
  };

  if (hasAny(q, ["пятн", "гнил", "мягк", "опада", "боле", "проблем"])) return {
    topic: "symptoms",
    text: `Зафиксируйте у ${name} фото, дату и место появления симптома. Сравните последние поливы, подкормки, перестановки и температуру. Не меняйте сразу несколько условий: сначала исключите застой воды и видимых вредителей, затем наблюдайте динамику. Это справочная подсказка, а не точный диагноз.`,
  };

  if (hasAny(q, ["опрыск", "влажност", "сухой воздух"])) return {
    topic: "humidity",
    text: `Опрыскивание подходит не всем видам и даёт кратковременный эффект. Для ${name} сначала проверьте требования конкретного вида, держите листья чистыми и обеспечьте движение воздуха. Не оставляйте мокрыми цветы и опушённые листья, если карточка растения этого не рекомендует.`,
  };

  if (hasAny(q, ["токсич", "ядовит", "кошка", "собака", "ребен"])) return {
    topic: "safety",
    text: `Я не буду определять токсичность ${name} без проверенного источника. Не позволяйте ребёнку или животному контактировать с неизвестным растением. Если контакт или проглатывание уже произошло, обратитесь к врачу или ветеринару и сообщите точное название растения — локальный помощник не заменяет экстренную консультацию.`,
  };

  return {
    topic: "general",
    text: `Я работаю на этом устройстве бесплатно и без отправки данных в облачный ИИ. Уточните вопрос о ${name}: полив, свет, пересадка, подкормка, пожелтение листьев, вредители или размножение. Я дам локальную справочную подсказку, а историю действий лучше сохранить в карточке растения.`,
  };
}
