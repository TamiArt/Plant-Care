// ─── AI ASSISTANT SHEET ──────────────────────────────────────────────────────
interface AiMessage { role: "user" | "assistant"; text: string }

async function runAi(prompt: string, context: string, onChunk?: (t: string) => void): Promise<string> {
  const fullPrompt = `Ты — опытный садовод и эксперт по уходу за растениями. Отвечай кратко и по делу на русском языке.\n\nКонтекст растения: ${context}\n\nВопрос: ${prompt}`;

  // Try Chrome built-in Gemini Nano (window.ai)
  if ("ai" in window) {
    try {
      const ai = (window as unknown as { ai: { languageModel: { availability: () => Promise<string>; create: (o: object) => Promise<{ prompt: (p: string) => Promise<string> }> } } }).ai;
      const avail = await ai.languageModel.availability();
      if (avail === "readily" || avail === "downloadable") {
        const session = await ai.languageModel.create({ systemPrompt: "Ты эксперт садовод. Отвечай кратко на русском." });
        const result = await session.prompt(fullPrompt);
        return result;
      }
    } catch {
      // fall through
    }
  }

  // Try Ollama (local, free)
  try {
    const res = await fetch("http://localhost:11434/api/generate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ model: "llama3.2", prompt: fullPrompt, stream: false }),
    });
    if (res.ok) {
      const data = await res.json();
      return data.response ?? "Нет ответа.";
    }
  } catch {
    // fall through
  }

  return "ИИ-помощник недоступен. Убедитесь, что у вас установлен и запущен Ollama (ollama.com) или используется Chrome со встроенным Gemini Nano.";
}

function AiAssistantSheet({ up, onClose }: { up: UserPlant; onClose: () => void }) {
  const display = resolvePlantDisplay(up);
  const context = `${display.name}${display.latinName ? ` (${display.latinName})` : ""}. Полив каждые ${up.wateringInterval} дней. ${up.customDescription || ""}`;
  const [messages, setMessages] = useState<AiMessage[]>([
    { role: "assistant", text: `Привет! Я ваш ИИ-садовод 🌿 Задайте любой вопрос о ${display.name}.` }
  ]);
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const bottomRef = useRef<HTMLDivElement>(null);

  const send = async () => {
    const text = input.trim();
    if (!text || loading) return;
    setInput("");
    setMessages(prev => [...prev, { role: "user", text }]);
    setLoading(true);
    try {
      const reply = await runAi(text, context);
      setMessages(prev => [...prev, { role: "assistant", text: reply }]);
    } catch {
      setMessages(prev => [...prev, { role: "assistant", text: "Ошибка при обращении к ИИ." }]);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, loading]);

  const suggestions = [
    "Когда лучше пересаживать?",
    "Почему желтеют листья?",
    "Какое удобрение подходит?",
    "Как размножить?",
  ];

  return (
    <div className="fixed inset-0 z-50 flex flex-col">
      <div className="absolute inset-0 bg-foreground/40 backdrop-blur-sm" onClick={onClose} />
      <motion.div
        initial={{ y: "100%" }} animate={{ y: 0 }} exit={{ y: "100%" }}
        transition={{ type: "spring", damping: 28, stiffness: 280 }}
        className="relative mt-auto bg-background rounded-t-3xl w-full max-w-md mx-auto flex flex-col"
        style={{ maxHeight: "88vh" }}
      >
        <div className="flex justify-center pt-3 pb-1 flex-shrink-0">
          <div className="w-10 h-1 rounded-full bg-border" />
        </div>
        <div className="flex items-center gap-2 px-5 pb-3 border-b border-border flex-shrink-0">
          <div className="w-8 h-8 rounded-full bg-primary/10 flex items-center justify-center">
            <Bot size={16} className="text-primary" />
          </div>
          <div>
            <p className="text-sm font-semibold text-foreground">ИИ Садовод</p>
            <p className="text-[11px] text-muted-foreground">{display.name}</p>
          </div>
          <button onClick={onClose} className="ml-auto w-8 h-8 rounded-full bg-muted flex items-center justify-center">
            <X size={15} />
          </button>
        </div>

        <div className="flex-1 overflow-y-auto px-4 py-3 space-y-3">
          {messages.map((m, i) => (
            <div key={i} className={`flex ${m.role === "user" ? "justify-end" : "justify-start"}`}>
              <div className={`max-w-[85%] rounded-2xl px-3.5 py-2.5 text-sm leading-relaxed ${
                m.role === "user"
                  ? "bg-primary text-primary-foreground rounded-br-sm"
                  : "bg-secondary text-foreground rounded-bl-sm"
              }`}>
                {m.text}
              </div>
            </div>
          ))}
          {loading && (
            <div className="flex justify-start">
              <div className="bg-secondary rounded-2xl rounded-bl-sm px-3.5 py-2.5 flex gap-1 items-center">
                <Loader2 size={14} className="animate-spin text-muted-foreground" />
                <span className="text-sm text-muted-foreground">Думаю...</span>
              </div>
            </div>
          )}
          <div ref={bottomRef} />
        </div>

        {/* Quick suggestions */}
        {messages.length === 1 && (
          <div className="px-4 py-2 flex gap-2 overflow-x-auto scrollbar-hide flex-shrink-0">
            {suggestions.map(s => (
              <button key={s} onClick={() => { setInput(s); }}
                className="flex-shrink-0 text-xs bg-secondary text-foreground px-3 py-1.5 rounded-full border border-border"
              >
                {s}
              </button>
            ))}
          </div>
        )}

        <div className="px-4 pb-6 pt-2 border-t border-border flex gap-2 flex-shrink-0">
          <input
            value={input} onChange={e => setInput(e.target.value)}
            onKeyDown={e => e.key === "Enter" && send()}
            placeholder="Задайте вопрос о растении..."
            className="flex-1 bg-muted rounded-2xl px-4 py-2.5 text-sm outline-none placeholder:text-muted-foreground"
          />
          <button onClick={send} disabled={!input.trim() || loading}
            className="w-10 h-10 rounded-2xl bg-primary text-primary-foreground flex items-center justify-center disabled:opacity-40"
          >
            <Send size={16} />
          </button>
        </div>
      </motion.div>
    </div>
  );
}

