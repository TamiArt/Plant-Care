// ─── GBIF HOOK ───────────────────────────────────────────────────────────────
const GBIF = "https://api.gbif.org/v1";

interface GbifMatch {
  usageKey: number;
  scientificName: string;
  canonicalName: string;
  kingdom: string;
  phylum: string;
  class: string;
  order: string;
  family: string;
  genus: string;
  confidence: number;
  matchType: string;
  status: string;
}

interface GbifVernacular {
  vernacularName: string;
  language: string;
  source?: string;
}

interface GbifOccurrenceMedia {
  identifier: string;
  title?: string;
  creator?: string;
  rightsHolder?: string;
}

interface GbifData {
  match: GbifMatch;
  vernacularNames: GbifVernacular[];
  photos: GbifOccurrenceMedia[];
}

const LANG_LABELS: Record<string, string> = {
  rus: "Русский", eng: "English", deu: "Deutsch",
  fra: "Français", spa: "Español", ita: "Italiano",
  por: "Português", nld: "Nederlands", pol: "Polski",
  zho: "中文", jpn: "日本語",
};

function useGbif(latinName: string) {
  const [data, setData] = useState<GbifData | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);

  useEffect(() => {
    let cancelled = false;
    setData(null);
    setLoading(true);
    setError(false);

    async function fetchAll() {
      try {
        // 1. Match species by latin name
        const matchRes = await fetch(
          `${GBIF}/species/match?name=${encodeURIComponent(latinName)}&verbose=false`
        );
        if (!matchRes.ok) throw new Error("match failed");
        const match: GbifMatch = await matchRes.json();
        if (!match.usageKey || match.matchType === "NONE") throw new Error("no match");

        // 2. Vernacular names
        const vernRes = await fetch(
          `${GBIF}/species/${match.usageKey}/vernacularNames?limit=20`
        );
        const vernJson = await vernRes.json();
        const allNames: GbifVernacular[] = vernJson.results ?? [];
        // dedupe by language, keep first per lang, prefer known langs
        const seen = new Set<string>();
        const vernacularNames = allNames.filter(v => {
          if (!v.language || seen.has(v.language)) return false;
          seen.add(v.language);
          return true;
        }).slice(0, 8);

        // 3. Occurrence photos
        const occRes = await fetch(
          `${GBIF}/occurrence/search?taxonKey=${match.usageKey}&mediaType=StillImage&limit=6`
        );
        const occJson = await occRes.json();
        const photos: GbifOccurrenceMedia[] = [];
        for (const occ of (occJson.results ?? [])) {
          for (const m of (occ.media ?? [])) {
            if (m.type === "StillImage" && m.identifier) {
              photos.push({
                identifier: m.identifier,
                title: m.title,
                creator: m.creator ?? occ.recordedBy,
                rightsHolder: m.rightsHolder,
              });
              if (photos.length >= 4) break;
            }
          }
          if (photos.length >= 4) break;
        }

        if (!cancelled) setData({ match, vernacularNames, photos });
      } catch {
        if (!cancelled) setError(true);
      } finally {
        if (!cancelled) setLoading(false);
      }
    }

    fetchAll();
    return () => { cancelled = true; };
  }, [latinName]);

  return { data, loading, error };
}

