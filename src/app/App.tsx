// ─── TYPES ───────────────────────────────────────────────────────────────────
interface CatalogPlant {
  id: string;
  name: string;
  latinName: string;
  emoji: string;
  unsplashId: string;
  difficulty: "easy" | "medium" | "hard";
  watering: { summer: number; winter: number };
  tropical: boolean;
  needsMisting: boolean;
  description: string;
  careTip: string;
  diseases: string[];
  seasonalTips: string[];
  tags: string[];
}

type PlantLocation = "home" | "outdoor";

// Note content supports plain text, "- bullet", "[ ] checkbox", "[x] checked"
interface PlantNote {
  id: string;
  createdAt: string;
  content: string;
}

interface PlantReminder {
  id: string;
  title: string;
  date: string; // YYYY-MM-DD
  done: boolean;
}

interface UserPlant {
  id: string;
  catalogId: string | null;   // null = custom (not from catalog)
  // Custom plant fields — used when catalogId is null
  customName?: string;
  customLatinName?: string;
  customDescription?: string;
  customEmoji?: string;
  nickname: string;
  photo: string | null;
  wateringInterval: number;
  wateringHistory: string[];
  mistingHistory: string[];
  fertilizingInterval: number; // days, 0 = no schedule
  fertilizingHistory: string[];
  addedAt: string;
  location: PlantLocation;
  notes: PlantNote[];
  reminders: PlantReminder[];
}

interface WateringStatus {
  label: string;
  color: "green" | "yellow" | "red" | "gray";
  daysUntil: number;
  urgency: number;
}

